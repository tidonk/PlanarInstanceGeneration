#!/usr/bin/env python3
"""Rebuild the PGLib SCOPF flow boxplot, optionally refreshing its archived data."""

import argparse
import csv
import hashlib
import io
import math
import shutil
from pathlib import Path
import statistics
from zipfile import ZipFile

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
ROOT = REPOSITORY_ROOT
RESOURCES = ROOT / "resources/evaluation"
MEMBER = "planar-evaluation-20261110/code/check/results/ogdf_20261104_pglib_scopf_tal0/summary.csv"
SOURCE_SHA256 = "f06b019f014ebaa01b7ae3ccd09702887beb9f6d8c8e702d6e5a65e18cd311c2"
INPUT_SOURCE = MEMBER
INPUT_SHA256 = SOURCE_SHA256
METHODS = [
    ("random", "R", "*", 64, 1.3450886057939697),
    ("high_degree", "HD", "triangle*", 70, 2.8013928793068046),
    ("kamada_kawai", "KK", "square*", 53, .7016791439755666),
    ("heuristic_outer_face", "OF-H", "diamond*", 61, .9935307218902305),
    ("exact_outer_face", "OF-B", "triangle*", 62, 1.0489082471322644),
]


def data_path(method):
    return RESOURCES / "plot-data" / f"scopf-flow-{method}.dat"


def refresh(archive=None, summary=None, verify_recorded=False):
    global INPUT_SOURCE, INPUT_SHA256
    if summary is not None:
        raw = summary.read_bytes()
    else:
        with ZipFile(archive) as z:
            raw = z.read(MEMBER)
    if verify_recorded and hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("The archived SCOPF data differ from the verified paper results.")
    INPUT_SOURCE = str(summary) if summary is not None else MEMBER
    INPUT_SHA256 = hashlib.sha256(raw).hexdigest()
    rows = list(csv.DictReader(io.StringIO(raw.decode())))
    assert len(rows) == 500
    selected = [r for r in rows if r["state"] == "complete" and r["scopf_feasible"] == "True"]
    if verify_recorded:
        assert len(selected) == 310
    for index, (method, _, _, count, _) in enumerate(METHODS):
        group = [r for r in selected if r["strategy"] == method]
        assert group
        if verify_recorded:
            assert len(group) == count
        lines = ["artifact coupling_mean_mw inherited_mean_mw x y"]
        for row in group:
            assert float(row["coupling_branch_observation_fraction"]) == 1
            assert float(row["noncoupling_branch_observation_fraction"]) == 1
            numerator = float(row["coupling_mean_absolute_flow_mw"])
            denominator = float(row["noncoupling_mean_absolute_flow_mw"])
            assert numerator > 0 and denominator > 0
            seed = hashlib.sha256((method + row["artifact_stem"]).encode()).digest()[:8]
            x = index + .38 * (int.from_bytes(seed, "big") / 2**64 - .5)
            lines.append(f"{row['artifact_stem']} {numerator:.17g} {denominator:.17g} {x:.12g} {numerator/denominator:.17g}")
        data_path(method).write_text("\n".join(lines) + "\n")


def quantile(values, q):
    index = (len(values)-1)*q
    lower, upper = math.floor(index), math.ceil(index)
    return values[lower] + (index-lower)*(values[upper]-values[lower])


def build(verify_recorded=True):
    all_values = []
    for method, *_ in METHODS:
        with data_path(method).open() as stream:
            all_values.extend(float(row['y']) for row in csv.DictReader(stream, delimiter=' '))
    assert all_values and all(math.isfinite(value) and value > 0 for value in all_values)
    lower, upper = (.16, 12.5) if verify_recorded else (min(.16, min(all_values) * .9), max(12.5, max(all_values) * 1.1))
    lines = [
        "% Generated by check/scripts/export_paper_scopf_flow_boxplot.py.",
        f"% Source: {INPUT_SOURCE}",
        f"% Source SHA256: {INPUT_SHA256}",
        "% Complete feasible SCOPF runs; no switching or voltage normalization.",
        "% Quartiles and 1.5-IQR whiskers use untransformed ratios.",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=.97\linewidth,height=.5567\linewidth,",
        rf"  xmin=-.55,xmax=4.55,ymin={lower:.12g},ymax={upper:.12g},",
        r"  ymode=log,log basis y=2,",
        r"  xtick={0,1,2,3,4},",
        r"  xticklabels={R,HD,KK,OF-H,OF-B},",
        r"  ytick={.25,.5,1,2,4,8},yticklabels={$0.25$,$0.5$,$1$,$2$,$4$,$8$},",
        r"  minor y tick num=0,",
        r"  axis lines*=left,axis line style={line width=.5pt},",
        r"  tick label style={font=\scriptsize},label style={font=\scriptsize},",
        r"  ylabel={\shortstack{Mean absolute flow ratio\\(coupling / inherited)}},",
        r"  ymajorgrids=true,grid style={gray!20,line width=.3pt},",
        r"]",
        r"\draw[black,dashed,line width=.55pt] (axis cs:-.55,1) -- (axis cs:4.55,1);",
    ]
    for index, (method, label, marker, count, expected) in enumerate(METHODS):
        rows = list(csv.DictReader(data_path(method).open(), delimiter=" "))
        values = sorted(float(r["y"]) for r in rows)
        assert values and len({r['artifact'] for r in rows}) == len(values)
        if verify_recorded:
            assert len(values) == count
            assert min(values) > .16 and max(values) < 12.5
        assert all(math.isclose(float(r['y']), float(r['coupling_mean_mw'])/float(r['inherited_mean_mw']), rel_tol=1e-12) for r in rows)
        assert all(abs(float(r['x'])-index) <= .19 for r in rows)
        if verify_recorded:
            assert math.isclose(statistics.median(values), expected, rel_tol=1e-12)
        q1, median, q3 = [quantile(values, q) for q in [.25,.5,.75]]
        iqr = q3-q1
        lo = min(v for v in values if v >= q1-1.5*iqr)
        hi = max(v for v in values if v <= q3+1.5*iqr)
        color = f"pigMethod{index}"
        rotate = ",mark options={rotate=180}" if index == 4 else ""
        path = data_path(method).relative_to(ROOT).as_posix()
        lines.append(rf"\addplot[only marks,mark={marker},mark size=1.15pt,color={color},opacity=.45{rotate}] table[x=x,y=y] {{{path}}};")
        for x1,y1,x2,y2 in [(index,lo,index,q1),(index,q3,index,hi),
                             (index-.13,lo,index+.13,lo),(index-.13,hi,index+.13,hi)]:
            lines.append(rf"\draw[color={color},line width=.45pt] (axis cs:{x1:.12g},{y1:.12g}) -- (axis cs:{x2:.12g},{y2:.12g});")
        lines.append(rf"\path[draw={color},fill={color},fill opacity=.16,draw opacity=1,line width=.5pt] (axis cs:{index-.25:.12g},{q1:.12g}) rectangle (axis cs:{index+.25:.12g},{q3:.12g});")
        lines.append(rf"\draw[black,line width=.65pt] (axis cs:{index-.25:.12g},{median:.12g}) -- (axis cs:{index+.25:.12g},{median:.12g});")
        print(f"{label}: {len(values)} solutions, median {median:.6f}")
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    (RESOURCES / "fig-eval-scopf-flows.tikz").write_text("\n".join(lines) + "\n")


def main():
    global ROOT, RESOURCES
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper-dir", type=Path, required=True,
                        help="Destination for resources/evaluation; existing flow files are not overwritten.")
    parser.add_argument("--data-dir", type=Path,
                        default=REPOSITORY_ROOT / "reproduction/flow-plot-data",
                        help="Directory containing the saved per-instance means.")
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--archive", type=Path, help="Read the SCOPF summary from a private evaluation ZIP.")
    source.add_argument("--summary", type=Path, help="Read a SCOPF summary CSV from a completed experiment.")
    parser.add_argument("--verify-paper-results", action="store_true", help="Require the recorded paper checksum and statistics.")
    args = parser.parse_args()
    if not (args.archive or args.summary) and not args.data_dir.is_dir():
        parser.error("provide --summary, --archive, or --data-dir with saved measurements")
    ROOT = args.paper_dir.resolve()
    RESOURCES = ROOT / "resources/evaluation"
    targets = [RESOURCES / "fig-eval-scopf-flows.tikz"] + [data_path(m[0]) for m in METHODS]
    if any(p.exists() for p in targets):
        parser.error("choose a destination without existing scopf flow files")
    (RESOURCES / "plot-data").mkdir(parents=True, exist_ok=True)
    if args.archive or args.summary:
        refresh(args.archive, args.summary, args.verify_paper_results)
    else:
        for method, *_ in METHODS:
            shutil.copyfile(args.data_dir / data_path(method).name, data_path(method))
    build(verify_recorded=args.verify_paper_results or not (args.archive or args.summary))


if __name__ == "__main__":
    main()
