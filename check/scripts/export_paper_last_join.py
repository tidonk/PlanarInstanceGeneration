#!/usr/bin/env python3
"""Export the individual windows of the appendix example's last join."""
import argparse
import ast
import csv
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]

_SUBTLE_SOURCE_COLORS = {
    "0072B2": "5B7FA3",
    "E69F00": "C98B5A",
    "009E73": "5E9B76",
    "CC79A7": "A77C9E",
    "56B4E9": "78AFC2",
}


def apply_subtle_source_colors(fragment):
    for original, replacement in _SUBTLE_SOURCE_COLORS.items():
        fragment = fragment.replace(
            f"{{HTML}}{{{original}}}", f"{{HTML}}{{{replacement}}}"
        )
    return fragment


def extract_composite_graph(fragment):
    graph_start = fragment.find("% Generated by planar-instance-generation.")
    graph_end = fragment.find(r"\end{tikzpicture}", graph_start)
    if graph_start < 0 or graph_end < graph_start:
        raise ValueError("composite graph block not found")
    graph_end += len(r"\end{tikzpicture}")
    return fragment[graph_start:graph_end] + "\n"


def compile_composite(source_tikz, output_pdf):
    fragment = source_tikz.read_text(encoding="utf-8")
    fragment = extract_composite_graph(fragment)
    fragment = apply_subtle_source_colors(fragment)
    with tempfile.TemporaryDirectory(prefix="pig-composite-") as temporary_name:
        temporary = Path(temporary_name)
        (temporary / "full.tikz").write_text(fragment, encoding="utf-8")
        (temporary / "full.tex").write_text(
            r"\documentclass[border=1pt]{standalone}" "\n"
            r"\usepackage{tikz}" "\n"
            r"\begin{document}" "\n"
            r"\input{full.tikz}" "\n"
            r"\end{document}" "\n",
            encoding="utf-8",
        )
        result = subprocess.run(
            ["pdflatex", "-interaction=batchmode", "-halt-on-error", "full.tex"],
            cwd=temporary, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
        )
        if result.returncode:
            raise RuntimeError(result.stdout[-4000:])
        shutil.copyfile(temporary / "full.pdf", output_pdf)

def compile_panel(paper, tikz_path):
    pdf_path = tikz_path.with_suffix(".pdf")
    if pdf_path.is_file() and pdf_path.stat().st_mtime >= tikz_path.stat().st_mtime:
        return pdf_path
    relative = tikz_path.relative_to(paper).as_posix()
    with tempfile.TemporaryDirectory(prefix="pig-last-join-") as temporary_name:
        temporary = Path(temporary_name)
        source = temporary / (tikz_path.stem + ".tex")
        source.write_text("\\documentclass[tikz,border=1pt]{standalone}\n\\usepackage{xcolor}\n\\begin{document}\n\\input{" + relative + "}\n\\end{document}\n")
        result = subprocess.run(
            ["pdflatex", "-interaction=batchmode", "-halt-on-error",
             "-output-directory", str(temporary), str(source)],
            cwd=paper, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
        )
        if result.returncode:
            raise RuntimeError(result.stdout[-4000:])
        shutil.copyfile(temporary / (tikz_path.stem + ".pdf"), pdf_path)
    return pdf_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paper", type=Path)
    parser.add_argument("--run", type=Path, required=True)
    parser.add_argument("--input", type=int, required=True)
    args = parser.parse_args()
    paper = args.paper.resolve()
    run = args.run.resolve()
    labels = {
        "random": "Random", "high_degree": "High degree", "kamada_kawai": "Kamada--Kawai",
        "heuristic_outer_face": "Heuristic outer face", "exact_outer_face": "Exact outer face",
    }
    rows = [row for row in csv.DictReader((run / "tables/accepted_instances.csv").open())
            if int(row["output_index"]) == args.input]
    if {row["strategy"] for row in rows} != set(labels) or len(rows) != 5:
        raise ValueError("Example must contain exactly one composite per method")
    output = []
    for row in rows:
        strategy, stem = row["strategy"], row["artifact_stem"]
        target = paper / "resources/evaluation/last-join" / strategy
        target.mkdir(parents=True, exist_ok=True)
        piece_sizes = tuple(ast.literal_eval(row["target_nodes"]))
        last_stage = len(piece_sizes) - 1
        stage = run / "plots/merged" / stem / f"stage_{last_stage:03d}"
        panels = json.loads((stage / f"merge_stage_{last_stage:03d}.json").read_text())["panels"]
        if len(panels) < 3:
            raise ValueError("a merge plot needs input, edge, and final panels")
        short = {"random":"random", "high_degree":"high-degree", "kamada_kawai":"kamada-kawai",
                 "heuristic_outer_face":"heuristic", "exact_outer_face":"exact"}[strategy]
        compile_composite(run / "plots/composite" / stem / "full.tikz",
                          paper / f"resources/evaluation/fig-app-example-composites-{short}.pdf")
        placement = "!htbp" if strategy == "random" else "p"
        output.append(f"\\begin{{figure}}[{placement}]\n\\centering\n")
        for index, panel in enumerate(panels):
            name = Path(panel["tikz"]).stem
            source = stage / (name + ".tikz")
            (target / (name + ".tikz")).write_text(apply_subtle_source_colors(source.read_text()))
            tikz_path = target / (name + ".tikz")
            pdf_path = compile_panel(paper, tikz_path)
            row_length = 3 if len(panels) >= 7 else (2 if index < 4 else 3)
            width = "0.315" if row_length == 3 else "0.48"
            title = (
                rf"\(C_{last_stage}\) and \(G_{last_stage+1}\)" if index == 0
                else rf"Final composite \(C_{last_stage+1}\)" if index == len(panels) - 1
                else f"{index} coupling edge{'s' if index != 1 else ''} added"
            )
            relative = pdf_path.relative_to(paper).as_posix()
            output.append(
                fr"\begin{{subfigure}}[t]{{{width}\textwidth}}" + "\n"
                + fr"\centering\includegraphics[width=\linewidth]{{{relative}}}" + "\n"
                + fr"\caption{{{title}}}\end{{subfigure}}" + "\n"
            )
            row_end = (
                (index + 1) % 3 == 0
                if len(panels) >= 7
                else index in (1, 3)
            )
            output.append(
                "\\par\\medskip\n"
                if row_end and index < len(panels) - 1
                else "\\hfill\n"
                if index < len(panels) - 1
                else ""
            )
        output.append("\\caption{" + labels[strategy] + "}\n\\end{figure}\n\\clearpage\n")
        print("Exported", strategy, flush=True)
    (paper / "resources/evaluation/fig-app-last-join.tex").write_text("".join(output))


if __name__ == "__main__":
    main()
