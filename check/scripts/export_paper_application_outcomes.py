#!/usr/bin/env python3
"""Export SCOTS and SND outcome counts with the source reference sets."""

import argparse
from collections import Counter
import csv
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from check.scripts.export_paper_exact_tables import select_source_rows

RESULTS = ROOT / "check/results"
PREFIX = "merge_count_600_3600_20260911_log2"
METHODS = ("random", "high_degree", "kamada_kawai", "heuristic_outer_face", "exact_outer_face")
CATEGORIES = ("feasible", "infeasible", "unknown")


def outcome(row, domain):
    status = row.get("termination_status", "")
    state = row.get("state", "")
    if state == "missing":
        raise ValueError("cannot export missing application results")
    if status.endswith("ERROR") or state in ("error", "failed", "launch_error", "process_error"):
        return "unknown"
    field = "scopf_feasible" if domain == "scots" else "has_finite_objective"
    if state == "complete" and row.get(field) == "True":
        if not math.isfinite(float(row["objective_value"])):
            raise ValueError("feasible result has a nonfinite objective")
        return "feasible"
    if state == "complete" and status == "INFEASIBLE":
        return "infeasible"
    return "unknown"


def read_rows(path):
    with path.open(newline="") as stream:
        data = list(csv.DictReader(stream))
    if len({row["artifact_stem"] for row in data}) != len(data):
        raise ValueError(f"duplicate results in {path}")
    if any(float(row["time_limit_seconds"]) != 10800 for row in data):
        raise ValueError(f"unexpected solver limit in {path}")
    return data


def render(data, source, domain):
    composites = [[row for row in data if row["strategy"] == method] for method in METHODS]
    groups = ([source] if source is not None else []) + composites
    if len(data) != 500 or any(len(group) != 100 for group in composites):
        raise ValueError("expected 100 composites per method")
    if source is not None and (not source or any(row["strategy"] != "source" for row in source)):
        raise ValueError("invalid source reference set")
    positions = ((r"\pigSourceY",) if source is not None else ()) + (0, 1, 2, 3, 4)
    counts = [Counter(outcome(row, domain) for row in group) for group in groups]
    tex = [
        "% Generated by check/scripts/export_paper_application_outcomes.py.",
        r"\begingroup",
        r"\pigSetRowSpacing",
        r"\begin{tikzpicture}", r"\begin{axis}[",
        r"  set layers=standard,clip=false,xbar stacked,/pgf/bar width=\pigBarWidth,",
        (r"  ymin=\pigSourceYMin,ymax=4.64,ytick={\pigSourceY,0,1,2,3,4},y dir=reverse,"
         if source is not None else r"  ymin=-.64,ymax=4.64,ytick={0,1,2,3,4},y dir=reverse,"),
        (r"  yticklabels={Source,R,HD,KK,OF-H,OF-B}," if source is not None
         else r"  yticklabels={R,HD,KK,OF-H,OF-B},"),
        r"  width=.97\linewidth,height=\pigSourcePlotHeight,",
        r"  xmin=0,xmax=100,xtick={0,25,50,75,100},",
        r"  axis lines*=left,axis line style={line width=.5pt},",
        r"  tick label style={font=\scriptsize},label style={font=\scriptsize},",
        r"  xlabel={Number of instances},xmajorgrids=true,grid style={gray!18,line width=.3pt},",
        r"  legend style={font=\scriptsize,legend columns=3,draw=none,",
        r"    /tikz/every even column/.append style={column sep=3mm}},",
    ]
    if domain == "scots":
        tex.append(r"  legend to name=applicationoutcomelegend,")
    tex.append("]")
    if domain == "scots":
        for style, label in (("fill=black", "Feasible"), ("pig infeasible=black", "Infeasible"),
                             ("fill=white", "No solution")):
            tex.extend((rf"\addlegendimage{{area legend,draw=black,{style}}}", rf"\addlegendentry{{{label}}}"))
    for index, values in enumerate(counts):
        color = f"pigMethod{(5 if index == 0 else index - 1) if source is not None else index}"
        styles = (f"fill={color}", f"pig infeasible={color}", "fill=white")
        for category, style in zip(CATEGORIES, styles):
            coords = " ".join(f"({values[category] if j == index else 0},{y})" for j, y in enumerate(positions))
            tex.append(rf"\addplot[draw={color},{style},forget plot] coordinates {{{coords}}};")
    tex.extend((r"\pgfplotsextra{", r"\begin{pgfonlayer}{axis foreground}"))
    for y, values in zip(positions, counts):
        start = 0
        for category in CATEGORIES:
            value = values[category]
            if value:
                style = "text=white,inner sep=0pt" if category == "feasible" else "text=black,fill=white,inner sep=1pt"
                if source is not None and y == positions[0] and value < 4:
                    style += ",anchor=south,yshift=6pt"
                tex.append(rf"\node[font=\scriptsize,{style}] at (axis cs:{start + value / 2:g},{y}) {{{value}}};")
            start += value
    tex.extend((r"\end{pgfonlayer}", "}", r"\end{axis}", r"\end{tikzpicture}", r"\endgroup", ""))
    return "\n".join(tex), counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paper", type=Path)
    parser.add_argument("--scots-run", default=f"{PREFIX}_pglib_scots_tal1_10800")
    parser.add_argument("--scots-source-run", default="pglib_source_scots_tal1_10800")
    parser.add_argument("--domain", choices=("all", "scots", "snd"), default="all")
    args = parser.parse_args()
    runs = {
        "scots": (args.scots_run, args.scots_source_run),
        "snd": (f"{PREFIX}_snd_benders", "snd_source_benders_10800"),
    }
    for domain, (run, source_run) in runs.items():
        if args.domain not in ("all", domain):
            continue
        generation_domain = "pglib" if domain == "scots" else "snd"
        source = select_source_rows(
            read_rows(RESULTS / source_run / "summary.csv"),
            RESULTS / f"{PREFIX}_{generation_domain}",
        )
        tex, counts = render(read_rows(RESULTS / run / "summary.csv"), source, domain)
        (args.paper / "resources/evaluation" / f"fig-eval-application-outcomes-{domain}.tikz").write_text(tex)
        print(domain, dict(zip(("source",) + METHODS, map(dict, counts))))


if __name__ == "__main__":
    main()
