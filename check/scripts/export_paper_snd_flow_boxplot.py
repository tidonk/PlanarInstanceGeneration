#!/usr/bin/env python3
"""Rebuild the SND flow boxplot from saved means or verified solver summaries."""

import argparse
import csv
import hashlib
import json
import math
import shutil
from pathlib import Path
import statistics

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
ROOT = REPOSITORY_ROOT
RESOURCES = ROOT / "resources/evaluation"
SOURCE_SHA256 = "5445713e267dbe23d75bf5e90f5f2a17b9851c54685053870d17d0766d23bb0b"
INPUT_SOURCE = "recorded snd_flow_mcmcf_20261112/results/*/summary.json"
INPUT_SHA256 = SOURCE_SHA256
METHODS = [
    ("random", "R", "*", .09414272432471979),
    ("high_degree", "HD", "triangle*", .5119260475224587),
    ("kamada_kawai", "KK", "square*", .044292110618169095),
    ("heuristic_outer_face", "OF-H", "diamond*", .111330863482922),
    ("exact_outer_face", "OF-B", "triangle*", .1047480584286017),
]


def data_path(method):
    return RESOURCES / "plot-data" / f"snd-flow-{method}.dat"


def display_y(value):
    """Linear on [0, .001], logarithmic above, continuous at .001."""
    return value / .001 if value <= .001 else 1 + math.log10(value / .001)


def refresh(source, verify_recorded=False):
    global INPUT_SOURCE, INPUT_SHA256
    raw = source.read_bytes()
    if verify_recorded and hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("The solver summaries differ from the verified final SND results.")
    INPUT_SOURCE = str(source)
    INPUT_SHA256 = hashlib.sha256(raw).hexdigest()
    rows = json.loads(raw)["results"]
    assert len(rows) == len({r["stem"] for r in rows}) == 500
    assert all(r["success"] and r["primary_status"] == r["secondary_status"] == 2 for r in rows)
    for index, (method, _, _, _) in enumerate(METHODS):
        group = sorted((r for r in rows if r["strategy"] == method), key=lambda r: r["stem"])
        assert len(group) == len({r["input_index"] for r in group}) == 100
        lines = ["artifact coupling_mean inherited_mean x ratio y"]
        for row in group:
            numerator, denominator = row["coupling"]["mean"], row["inherited"]["mean"]
            assert numerator >= 0 and denominator > 0
            ratio = numerator / denominator
            assert math.isfinite(ratio) and math.isclose(ratio, row["ratios"]["mean"], rel_tol=1e-12)
            seed = hashlib.sha256((method + row["stem"]).encode()).digest()[:8]
            x = index + .38 * (int.from_bytes(seed, "big") / 2**64 - .5)
            lines.append(f"{row['stem']} {numerator:.17g} {denominator:.17g} {x:.12g} {ratio:.17g} {display_y(ratio):.17g}")
        data_path(method).write_text("\n".join(lines) + "\n")


def quantile(values, q):
    index = (len(values) - 1) * q
    lower, upper = math.floor(index), math.ceil(index)
    return values[lower] + (index - lower) * (values[upper] - values[lower])


def build(verify_recorded=True):
    all_values = []
    for method, *_ in METHODS:
        with data_path(method).open() as stream:
            all_values.extend(float(row['ratio']) for row in csv.DictReader(stream, delimiter=' '))
    assert all_values and all(math.isfinite(value) and value >= 0 for value in all_values)
    upper = 4.77815125038 if verify_recorded else max(4.77815125038, display_y(max(all_values)) + .1)
    lines = [
        "% Generated by check/scripts/export_paper_snd_flow_boxplot.py.",
        f"% Source: {INPUT_SOURCE}",
        f"% Source SHA256: {INPUT_SHA256}",
        "% All 500 runs optimal in both steps. Fixed inherited capacities and one coupling module per edge.",
        "% Minimum routing cost, then minimum total flow; no failures. Sum both directions and all commodities.",
        "% Quartiles and 1.5-IQR whiskers use raw ratios. Display is linear below .001, logarithmic above.",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=.97\linewidth,height=.5567\linewidth,",
        rf"  xmin=-.55,xmax=4.55,ymin=-.15,ymax={upper:.12g},",
        r"  xtick={0,1,2,3,4},xticklabels={R,HD,KK,OF-H,OF-B},",
        r"  ytick={0,1,2,3,4,4.69897000434},yticklabels={$0$,$0.001$,$0.01$,$0.1$,$1$,$5$},",
        r"  axis lines*=left,axis line style={line width=.5pt},",
        r"  tick label style={font=\scriptsize},label style={font=\scriptsize},",
        r"  ylabel={\shortstack{Mean aggregate flow ratio\\(coupling / inherited)}},",
        r"  ymajorgrids=true,grid style={gray!20,line width=.3pt},",
        r"]",
        r"\draw[black,dashed,line width=.55pt] (axis cs:-.55,4) -- (axis cs:4.55,4);",
    ]
    for index, (method, label, marker, expected) in enumerate(METHODS):
        with data_path(method).open() as f:
            rows = list(csv.DictReader(f, delimiter=" "))
        values = sorted(float(r["ratio"]) for r in rows)
        assert len(values) == len({r["artifact"] for r in rows}) == 100
        assert min(values) >= 0
        if verify_recorded:
            assert max(values) < 6
        for row in rows:
            ratio = float(row["ratio"])
            assert math.isclose(ratio, float(row["coupling_mean"]) / float(row["inherited_mean"]), rel_tol=1e-12)
            assert math.isclose(float(row["y"]), display_y(ratio), rel_tol=1e-12)
            assert abs(float(row["x"]) - index) <= .19
        if verify_recorded:
            assert math.isclose(statistics.median(values), expected, rel_tol=1e-12)
        q1, median, q3 = [quantile(values, q) for q in [.25, .5, .75]]
        iqr = q3 - q1
        lo = min(v for v in values if v >= q1 - 1.5 * iqr)
        hi = max(v for v in values if v <= q3 + 1.5 * iqr)
        lo, q1, median, q3, hi = map(display_y, [lo, q1, median, q3, hi])
        color = f"pigMethod{index}"
        rotate = ",mark options={rotate=180}" if index == 4 else ""
        path = data_path(method).relative_to(ROOT).as_posix()
        lines.append(rf"\addplot[only marks,mark={marker},mark size=1.15pt,color={color},opacity=.45{rotate}] table[x=x,y=y] {{{path}}};")
        for x1, y1, x2, y2 in [(index, lo, index, q1), (index, q3, index, hi),
                              (index-.13, lo, index+.13, lo), (index-.13, hi, index+.13, hi)]:
            lines.append(rf"\draw[color={color},line width=.45pt] (axis cs:{x1:.12g},{y1:.12g}) -- (axis cs:{x2:.12g},{y2:.12g});")
        lines.append(rf"\path[draw={color},fill={color},fill opacity=.16,draw opacity=1,line width=.5pt] (axis cs:{index-.25:.12g},{q1:.12g}) rectangle (axis cs:{index+.25:.12g},{q3:.12g});")
        lines.append(rf"\draw[black,line width=.65pt] (axis cs:{index-.25:.12g},{median:.12g}) -- (axis cs:{index+.25:.12g},{median:.12g});")
        print(f"{label}: {len(values)} solutions, median {statistics.median(values):.6f}")
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    (RESOURCES / "fig-eval-snd-flows.tikz").write_text("\n".join(lines) + "\n")


def main():
    global ROOT, RESOURCES
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper-dir", type=Path, required=True,
                        help="Destination for resources/evaluation; existing flow files are not overwritten.")
    parser.add_argument("--data-dir", type=Path,
                        default=REPOSITORY_ROOT / "reproduction/flow-plot-data",
                        help="Directory containing the saved per-instance means.")
    parser.add_argument("--results", type=Path, help="Read complete results.json from collect_snd_flow_measurements.py.")
    parser.add_argument("--verify-paper-results", action="store_true", help="Require the recorded paper checksum and statistics.")
    args = parser.parse_args()
    if args.results is None and not args.data_dir.is_dir():
        parser.error("provide --results or --data-dir with saved measurements")
    ROOT = args.paper_dir.resolve()
    RESOURCES = ROOT / "resources/evaluation"
    targets = [RESOURCES / "fig-eval-snd-flows.tikz"] + [data_path(m[0]) for m in METHODS]
    if any(p.exists() for p in targets):
        parser.error("choose a destination without existing snd flow files")
    (RESOURCES / "plot-data").mkdir(parents=True, exist_ok=True)
    if args.results:
        refresh(args.results, args.verify_paper_results)
    else:
        for method, *_ in METHODS:
            shutil.copyfile(args.data_dir / data_path(method).name, data_path(method))
    build(verify_recorded=args.verify_paper_results or args.results is None)


if __name__ == "__main__":
    main()
