#!/usr/bin/env python3
"""Export absolute and relative SCOPF base-case flow statistics."""

from __future__ import annotations

import argparse
import csv
import math
import json
from pathlib import Path
from statistics import median


ROOT = Path(__file__).resolve().parents[2]
METHODS = (
    ("random", "R"),
    ("high_degree", "HD"),
    ("kamada_kawai", "KK"),
    ("heuristic_outer_face", "OF-H"),
    ("exact_outer_face", "OF-B"),
)
DEFAULT_SOURCE_RUN = "merge_count_600_3600_20260911_log2_pglib_scopf"
DEFAULT_FLOW_RUN = "merge_count_600_3600_20260911_log2_pglib_scopf_flow_profile"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paper", type=Path)
    parser.add_argument(
        "--source-summary",
        type=Path,
        default=ROOT / "check/results" / DEFAULT_SOURCE_RUN / "summary.csv",
    )
    parser.add_argument(
        "--flow-summary",
        type=Path,
        default=ROOT / "check/results" / DEFAULT_FLOW_RUN / "summary.csv",
    )
    return parser.parse_args()


def read_rows(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        raise SystemExit(f"missing summary: {path}")
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def number(row: dict[str, str], field: str) -> float:
    try:
        value = float(row[field])
    except (KeyError, ValueError) as error:
        raise SystemExit(
            f"missing finite {field} for {row.get('artifact_stem', 'unknown')}"
        ) from error
    if not math.isfinite(value):
        raise SystemExit(
            f"nonfinite {field} for {row.get('artifact_stem', 'unknown')}"
        )
    return value


def relative_statistics(row: dict[str, str]) -> tuple[float, float, float]:
    reference = number(row, "noncoupling_mean_absolute_flow_mw")
    if reference <= 0:
        raise ValueError("mean inherited-branch flow must be positive")
    return tuple(number(row, field) / reference for field in (
        "coupling_mean_absolute_flow_mw",
        "coupling_p95_absolute_flow_mw",
        "coupling_maximum_absolute_flow_mw",
    ))


def positive_relative_flows(row: dict[str, str]) -> int:
    path = Path(row["summary_file"])
    # Use the packaged result when an original machine path was recorded.
    if path.is_absolute() and "/check/results/" in str(path):
        path = ROOT / "check/results" / str(path).split("/check/results/", 1)[1]
    if not path.is_absolute():
        path = ROOT / path
    data = json.loads((path.parent / "adapter_result.json").read_text())
    values = data["rating_normalization_validation"]["maximum_absolute_flow_by_branch_mw"]
    if len(values) != int(number(row, "expected_coupling_branch_count")):
        raise ValueError("incomplete coupling flow observations")
    reference = number(row, "noncoupling_mean_absolute_flow_mw")
    relative_statistics(row)  # validates the reference and all reported statistics
    return sum(float(flow) / reference > 1e-8 for flow in values.values())


def main() -> None:
    args = parse_args()
    source = read_rows(args.source_summary)
    flows = read_rows(args.flow_summary)
    if len(source) != 500:
        raise SystemExit(f"expected 500 source rows, found {len(source)}")
    feasible = {
        row["artifact_stem"]
        for row in source
        if row["state"] == "complete" and row["scopf_feasible"] == "True"
    }
    if args.flow_summary.resolve() == args.source_summary.resolve():
        flows = [row for row in flows if row["artifact_stem"] in feasible]
    observed = {row["artifact_stem"] for row in flows}
    if observed != feasible:
        raise SystemExit(
            "flow-profile rows do not match the feasible source rows: "
            f"missing={len(feasible - observed)}, extra={len(observed - feasible)}"
        )
    if any(
        row["state"] != "complete" or row["scopf_feasible"] != "True"
        for row in flows
    ):
        raise SystemExit("every flow-profile run must return a feasible solution")
    for row in flows:
        for field in (
            "coupling_branch_observation_fraction",
            "noncoupling_branch_observation_fraction",
        ):
            if not math.isclose(number(row, field), 1.0):
                raise SystemExit(
                    f"incomplete {field} for {row.get('artifact_stem', 'unknown')}"
                )

    lines = [
        "% Generated by check/scripts/export_paper_scopf_flows.py.",
        r"\begin{tabular}{lrrrrrrrrrr}",
        r"\toprule",
        r"\multicolumn{4}{c}{} & \multicolumn{4}{c}{Absolute flow [MW]} & \multicolumn{3}{c}{Relative flow}\\",
        r"\cmidrule(lr){5-8}\cmidrule(lr){9-11}",
        r"Method & $N$ & $\sum |M|$ & $M_{>0}$ & "
        r"$\widetilde{\bar f}_M$ & $\widetilde q_{.95,M}$ & "
        r"$\widetilde f_{\max,M}$ & $\widetilde{\bar f}_{E\setminus M}$ & "
        r"$\widetilde r_{\mathrm{mean}}$ & "
        r"$\widetilde r_{.95}$ & $\widetilde r_{\max}$\\",
        r"\midrule",
    ]
    for strategy, label in METHODS:
        rows = [row for row in flows if row["strategy"] == strategy]
        if not rows:
            raise SystemExit(f"no rows for strategy {strategy}")
        coupling_count = sum(
            int(number(row, "expected_coupling_branch_count")) for row in rows
        )
        positive_count = sum(
            positive_relative_flows(row) for row in rows
        )
        positive_share = 100.0 * positive_count / coupling_count
        absolute = [median(number(row, field) for row in rows) for field in (
            "coupling_mean_absolute_flow_mw", "coupling_p95_absolute_flow_mw",
            "coupling_maximum_absolute_flow_mw", "noncoupling_mean_absolute_flow_mw",
        )]
        ratios = [relative_statistics(row) for row in rows]
        medians = [100.0 * median(values[j] for values in ratios) for j in range(3)]
        lines.append(
            f"{label} & {len(rows)} & {coupling_count} & {positive_share:.1f}\\% & "
            + " & ".join(f"{value:.1f}" for value in absolute)
            + " & " + " & ".join(f"{value:.1f}\\%" for value in medians)
            + r"\\"
        )
    lines.extend((r"\bottomrule", r"\end{tabular}", ""))
    output = args.paper / "resources/evaluation/tab-app-scopf-flows.tex"
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
