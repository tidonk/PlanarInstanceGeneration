#!/usr/bin/env python3
"""Plot source, extracted, and composite medians and interquartile ranges."""

import argparse
import csv
from pathlib import Path

from matplotlib.ticker import MaxNLocator
import numpy as np

from check.scripts.export_paper_structure_tikz import load_domain, METHODS, LABELS, COLORS


FIELDS = (
    ("mean_degree", "Mean degree"),
    ("average_clustering", "Mean clustering"),
    ("diameter", "Diameter"),
    ("algebraic_connectivity", "Algebraic connectivity"),
    ("degree_assortativity", "Degree assortativity"),
)


def export_tikz(paper_dir, summaries):
    """Write two native subfigure inputs using the manuscript's fonts and colors."""
    labels = ("Sources", "Extracted", *LABELS)
    for domain, suffix in (("PGLib", "pglib"), ("SNDlib", "snd")):
        lines = [
            "% Generated by check/scripts/export_paper_extraction.py.",
            r"\begin{tikzpicture}",
            r"\begin{groupplot}[",
            r"  group style={group size=1 by 5,vertical sep=42pt},",
            r"  scale only axis,width=.73\linewidth,height=60pt,",
            r"  ymin=-.65,ymax=6.65,y dir=reverse,",
            r"  ytick={0,1,2,3,4,5,6},yticklabels={Sources,Extracted,R,HD,KK,OF-H,OF-B},",
            r"  axis lines*=left,y axis line style={draw=none},ytick style={draw=none},",
            r"  axis line style={line width=.5pt},",
            r"  tick label style={font=\scriptsize},",
            r"  title style={font=\small,at={(axis description cs:0,1)},anchor=south west,yshift=5pt},",
            r"  scaled x ticks=false,",
            r"  xticklabel style={/pgf/number format/fixed,/pgf/number format/precision=3},",
            r"  xmajorgrids=true,grid style={gray!18,line width=.3pt},",
            r"]",
        ]
        for key, title in FIELDS:
            entries = [next(r for r in summaries if r["domain"] == domain
                            and r["property"] == key and r["stage"] == stage)
                       for stage in labels]
            lower = min(r["q1"] for r in entries)
            upper = max(r["q3"] for r in entries)
            padding = .09 * (upper - lower)
            lower -= padding
            upper += padding
            ticks = MaxNLocator(nbins=4, integer=key == "diameter").tick_values(lower, upper)
            tick_string = ",".join(f"{t:.10g}" for t in ticks if lower <= t <= upper)
            lines.append(fr"\nextgroupplot[title={{{title}}},xmin={lower:.12g},xmax={upper:.12g},xtick={{{tick_string}}}]")
            lines.append(fr"\draw[gray!40,line width=.4pt] (axis cs:{lower:.12g},1.5) -- (axis cs:{upper:.12g},1.5);")
            for j, entry in enumerate(entries):
                color = ("black!80", "black!55")[j] if j < 2 else f"pigMethod{j-2}"
                q1, median, q3 = (entry[k] for k in ("q1", "median", "q3"))
                marker = "square*" if j < 2 else "*"
                fill = "white" if j == 1 else color
                lines.append(fr"\draw[{color},line width=1.25pt] (axis cs:{q1:.12g},{j}) -- (axis cs:{q3:.12g},{j});")
                lines.append(fr"\addplot[only marks,mark={marker},mark size=1.8pt,color={color},mark options={{fill={fill},line width=.6pt}}] coordinates {{({median:.12g},{j})}};")
        lines.extend([
            r"\end{groupplot}",
            r"\pgfresetboundingbox",
            r"\path[use as bounding box] ([xshift=-43pt,yshift=24pt]group c1r1.north west) rectangle ([xshift=14pt,yshift=-16pt]group c1r5.south east);",
            r"\end{tikzpicture}",
        ])
        destination = paper_dir / f"resources/evaluation/fig-app-extraction-{suffix}.tikz"
        destination.write_text("\n".join(lines) + "\n")
        print(destination)


def export(paper, roots):
    summaries = []
    for domain, root in roots.items():
        data = load_domain(root)
        stages = [("Sources", data["source"], ""),
                  ("Extracted", [r for r in data["structural"] if r["group"] == "Extracted subinstances"], "")]
        stages += [(label, [r for r in data["paired"] if r["strategy"] == method], "structural_")
                   for method, label in zip(METHODS, LABELS)]
        for key, _ in FIELDS:
            for label, records, prefix in stages:
                values = np.array([float(r[prefix + key]) for r in records if r[prefix + key] != ""])
                values = values[np.isfinite(values)]
                if not len(values): raise ValueError(f"No finite {key} values for {domain}/{label}")
                if key != "degree_assortativity" and len(values) != len(records):
                    raise ValueError(f"Missing {key} values for {domain}/{label}")
                q1, median, q3 = np.quantile(values, [.25,.5,.75])
                summaries.append(dict(domain=domain, stage=label, property=key, q1=q1, median=median, q3=q3))
    export_tikz(paper, summaries)
