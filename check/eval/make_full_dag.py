#!/usr/bin/env python3
"""Write the explicit per-cohort/per-method HTCondor DAG.

A generation node produces one paired five-method cohort.  Its five exact
skewness children become runnable immediately when that node succeeds; no
other cohort's generation state is involved in that release decision.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re


STRATEGIES = (
    "random",
    "high_degree",
    "kamada_kawai",
    "heuristic_outer_face",
    "exact_outer_face",
)
_SAFE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--experiment", default="full_shared4_300")
    parser.add_argument("--instances", type=int, default=100)
    parser.add_argument("--base-seed", type=int, default=0)
    parser.add_argument("--time-limit", type=int, default=300)
    parser.add_argument(
        "--output", type=Path, default=Path("check/eval/main.dag")
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not _SAFE.fullmatch(args.experiment):
        raise SystemExit("--experiment must be a safe path component")
    if args.instances < 1 or args.base_seed < 0:
        raise SystemExit("--instances must be positive and --base-seed nonnegative")
    if args.time_limit < 1:
        raise SystemExit("solver settings must be positive")

    experiment = args.experiment
    exact_output = f"{experiment}_pglib_exact"
    lines = [
        "# Generated by check/eval/make_full_dag.py.",
        "# Each PGLib cohort releases its five method-specific skewness jobs.",
        "",
        "JOB prepare check/eval/prepare.sub",
        "JOB gen_snd check/eval/snd.sub",
        "JOB report_pglib check/eval/report.sub",
        "JOB report_snd check/eval/report.sub",
        "JOB app_pglib check/eval/pglib_application.sub",
        "JOB app_snd check/eval/snd_application.sub",
        "",
        f'VARS gen_snd experiment="{experiment}"',
        f'VARS report_pglib experiment="{experiment}" dataset="pglib"',
        f'VARS report_snd experiment="{experiment}" dataset="snd"',
        f'VARS app_pglib experiment="{experiment}"',
        f'VARS app_snd experiment="{experiment}"',
        "",
        f"SCRIPT PRE app_pglib check/eval/prepare_application.sh pglib {experiment}",
        f"SCRIPT PRE app_snd check/eval/prepare_application.sh snd {experiment}",
        f"SCRIPT POST app_pglib check/eval/application_summary.sh pglib {experiment}",
        f"SCRIPT POST app_snd check/eval/application_summary.sh snd {experiment}",
        "",
        "PARENT prepare CHILD gen_snd",
        "PARENT gen_snd CHILD report_snd",
        "PARENT report_snd CHILD app_snd",
        "PARENT report_pglib CHILD app_pglib",
        "",
    ]

    for instance in range(1, args.instances + 1):
        tag = f"i{instance:03d}"
        generation = f"gen_pglib_{tag}"
        seed = args.base_seed + instance
        lines.extend(
            (
                f"JOB {generation} check/eval/pglib_one.sub",
                f'VARS {generation} experiment="{experiment}" instance="{instance}" seed="{seed}"',
                f"PARENT prepare CHILD {generation}",
            )
        )
        for strategy in STRATEGIES:
            skewness = f"skew_pglib_{tag}_{strategy}"
            lines.extend(
                (
                    f"JOB {skewness} check/eval/pglib_cohort_skewness.sub",
                    (
                        f'VARS {skewness} experiment="{experiment}" '
                        f'output_name="{exact_output}" instance="{instance}" '
                        f'seed="{args.base_seed}" strategy="{strategy}" '
                        f'time_limit="{args.time_limit}" '

                    ),
                    f"PARENT {generation} CHILD {skewness}",
                    f"PARENT {skewness} CHILD report_pglib",
                )
            )
        lines.append("")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(
        f"Wrote {args.output}: {args.instances} generation nodes and "
        f"{args.instances * len(STRATEGIES)} PGLib skewness nodes."
    )


if __name__ == "__main__":
    main()
