"""Publication-ready paired scatter plots."""

from __future__ import annotations

from dataclasses import asdict, dataclass
import json
import math
from pathlib import Path

from planar_instance_generation.plt.tikz import PlotArtifacts


@dataclass(frozen=True, slots=True)
class PairedScatterPoint:
    """One paired observation."""

    label: str
    x: float
    y: float
    highlighted: bool = False

    def __post_init__(self) -> None:
        if not self.label:
            raise ValueError("point label must not be empty")
        if not math.isfinite(self.x) or not math.isfinite(self.y):
            raise ValueError("point coordinates must be finite")


def write_paired_scatter(
    points: tuple[PairedScatterPoint, ...],
    output_base: str | Path,
    *,
    x_label: str,
    y_label: str,
    width_cm: float = 8.4,
    height_cm: float = 7.2,
    overwrite: bool = False,
) -> PlotArtifacts:
    """Write a paired scatter plot with an identity reference line."""

    if not points:
        raise ValueError("at least one point is required")
    if width_cm <= 0 or height_cm <= 0:
        raise ValueError("plot dimensions must be positive")
    base = Path(output_base)
    if base.suffix:
        raise ValueError("output_base must not have a file extension")
    artifacts = PlotArtifacts(
        tikz=base.with_suffix(".tikz"),
        standalone_tex=base.with_suffix(".tex"),
        coordinates_json=base.with_suffix(".json"),
    )
    existing = tuple(path.exists() for path in asdict(artifacts).values())
    if all(existing) and not overwrite:
        return artifacts
    if any(existing) and not overwrite:
        raise FileExistsError(f"incomplete paired-scatter artifact set at {base}")

    maximum = max(max(point.x, point.y) for point in points)
    axis_maximum = max(1.0, maximum * 1.05)
    ordinary = tuple(point for point in points if not point.highlighted)
    highlighted = tuple(point for point in points if point.highlighted)
    lines = [
        "% Generated by planar-instance-generation.\n",
        "\\pgfplotsset{compat=1.16}\n",
        "\\definecolor{pigBlue}{HTML}{0072B2}\n",
        "\\definecolor{pigOrange}{HTML}{D55E00}\n",
        "\\begin{tikzpicture}\n",
        "\\begin{axis}[\n",
        f"  width={width_cm:.3f}cm,height={height_cm:.3f}cm,\n",
        f"  xlabel={{{_escape(x_label)}}},ylabel={{{_escape(y_label)}}},\n",
        "  xmin=0,ymin=0,\n",
        f"  xmax={_number(axis_maximum)},ymax={_number(axis_maximum)},\n",
        "  axis equal image,\n",
        "  label style={font=\\small},tick label style={font=\\footnotesize},\n",
        "  axis line style={black!65},major grid style={black!12},grid=major,\n",
        "]\n",
        "\\addplot[black!55,dashed,thin,forget plot] coordinates "
        f"{{(0,0) ({_number(axis_maximum)},{_number(axis_maximum)})}};\n",
    ]
    if ordinary:
        lines.append(
            "\\addplot[only marks,mark=*,mark size=1.45pt,"
            "draw=pigBlue,fill=pigBlue,fill opacity=0.42,draw opacity=0.55] "
            f"coordinates {{{_coordinates(ordinary)}}};\n"
        )
    for point in highlighted:
        lines.append(
            "\\addplot[only marks,mark=diamond*,mark size=2.8pt,"
            "draw=pigOrange,fill=pigOrange] coordinates "
            f"{{({_number(point.x)},{_number(point.y)})}} "
            f"node[anchor=south west,font=\\footnotesize] {{{_escape(point.label)}}};\n"
        )
    lines.extend(["\\end{axis}\n", "\\end{tikzpicture}\n"])
    base.parent.mkdir(parents=True, exist_ok=True)
    artifacts.tikz.write_text("".join(lines), encoding="utf-8")
    artifacts.standalone_tex.write_text(
        "\\documentclass[border=2pt]{standalone}\n"
        "\\usepackage[T1]{fontenc}\n"
        "\\usepackage{lmodern}\n"
        "\\usepackage{pgfplots}\n"
        "\\begin{document}\n"
        "\\input{\\jobname.tikz}\n"
        "\\end{document}\n",
        encoding="utf-8",
    )
    artifacts.coordinates_json.write_text(
        json.dumps(
            {
                "kind": "paired_scatter",
                "identity_line": True,
                "x_label": x_label,
                "y_label": y_label,
                "points": [asdict(point) for point in points],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    return artifacts


def _coordinates(points: tuple[PairedScatterPoint, ...]) -> str:
    return " ".join(f"({_number(point.x)},{_number(point.y)})" for point in points)


def _number(value: float) -> str:
    return format(float(value), ".12g")


def _escape(value: str) -> str:
    replacements = {
        "\\": "\\textbackslash{}",
        "&": "\\&",
        "%": "\\%",
        "$": "\\$",
        "#": "\\#",
        "_": "\\_",
        "{": "\\{",
        "}": "\\}",
    }
    return "".join(replacements.get(character, character) for character in value)
