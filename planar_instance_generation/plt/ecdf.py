"""Publication-ready empirical cumulative-distribution plots."""

from __future__ import annotations

from dataclasses import asdict, dataclass
import json
import math
from pathlib import Path
import re
from typing import Iterable

from planar_instance_generation.plt.tikz import PlotArtifacts


_HEX_COLOR = re.compile(r"^#?[0-9A-Fa-f]{6}$")
_LINE_STYLES = ("solid", "dashed", "dashdotted", "densely dashed", "solid")


@dataclass(frozen=True, slots=True)
class EcdfSeries:
    """One empirical distribution."""

    label: str
    values: tuple[float, ...]
    color: str

    def __post_init__(self) -> None:
        if not self.label:
            raise ValueError("series label must not be empty")
        if not self.values or not all(math.isfinite(value) for value in self.values):
            raise ValueError("series values must be nonempty and finite")
        if not _HEX_COLOR.fullmatch(self.color):
            raise ValueError(f"invalid six-digit RGB color: {self.color!r}")


def write_ecdf(
    series: Iterable[EcdfSeries],
    output_base: str | Path,
    *,
    x_label: str,
    width_cm: float = 10.2,
    height_cm: float = 7.2,
    overwrite: bool = False,
) -> PlotArtifacts:
    """Write an ECDF as a TikZ fragment, standalone preview, and JSON data."""

    groups = tuple(series)
    if not groups:
        raise ValueError("at least one ECDF series is required")
    if width_cm <= 0 or height_cm <= 0:
        raise ValueError("plot dimensions must be positive")
    base = Path(output_base)
    if base.suffix:
        raise ValueError("output_base must not have a file extension")
    artifacts = PlotArtifacts(
        tikz=base.with_suffix(".tikz"),
        standalone_tex=base.with_suffix(".tex"),
        coordinates_json=base.with_suffix(".json"),
    )
    existing = tuple(path.exists() for path in asdict(artifacts).values())
    if all(existing) and not overwrite:
        return artifacts
    if any(existing) and not overwrite:
        raise FileExistsError(f"incomplete ECDF artifact set at {base}")

    maximum = max(max(group.values) for group in groups)
    axis_maximum = max(1.0, maximum)
    colors = tuple(group.color.lstrip("#").upper() for group in groups)
    steps = tuple(_steps(group.values, axis_maximum) for group in groups)
    base.parent.mkdir(parents=True, exist_ok=True)
    artifacts.tikz.write_text(
        _tikz(groups, steps, colors, x_label, axis_maximum, width_cm, height_cm),
        encoding="utf-8",
    )
    artifacts.standalone_tex.write_text(_standalone(), encoding="utf-8")
    artifacts.coordinates_json.write_text(
        json.dumps(
            {
                "kind": "ecdf",
                "x_label": x_label,
                "series": [
                    {
                        "label": group.label,
                        "color": f"#{color}",
                        "values": list(group.values),
                        "step_coordinates": [list(point) for point in points],
                    }
                    for group, color, points in zip(
                        groups, colors, steps, strict=True
                    )
                ],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    return artifacts


def _steps(
    values: tuple[float, ...], axis_maximum: float
) -> tuple[tuple[float, float], ...]:
    ordered = sorted(float(value) for value in values)
    counts: dict[float, int] = {}
    for value in ordered:
        counts[value] = counts.get(value, 0) + 1
    result = [(0.0, 0.0)]
    cumulative = 0
    total = len(ordered)
    for value, count in counts.items():
        result.append((value, cumulative / total))
        cumulative += count
        result.append((value, cumulative / total))
    result.append((axis_maximum, 1.0))
    return tuple(result)


def _tikz(
    groups: tuple[EcdfSeries, ...],
    steps: tuple[tuple[tuple[float, float], ...], ...],
    colors: tuple[str, ...],
    x_label: str,
    axis_maximum: float,
    width_cm: float,
    height_cm: float,
) -> str:
    lines = [
        "% Generated by planar-instance-generation.\n",
        "\\pgfplotsset{compat=1.16}\n",
    ]
    lines.extend(
        f"\\definecolor{{pigEcdf{index}}}{{HTML}}{{{color}}}\n"
        for index, color in enumerate(colors, start=1)
    )
    lines.extend(
        [
            "\\begin{tikzpicture}\n",
            "\\begin{axis}[\n",
            f"  width={width_cm:.3f}cm,height={height_cm:.3f}cm,\n",
            f"  xlabel={{{_escape(x_label)}}},ylabel={{Fraction of instances}},\n",
            "  xmin=0,ymin=0,ymax=1.02,\n",
            f"  xmax={_number(axis_maximum)},\n",
            "  label style={font=\\small},tick label style={font=\\footnotesize},\n",
            "  axis line style={black!65},major grid style={black!12},grid=major,\n",
            "  legend style={font=\\scriptsize,draw=none,fill=white,at={(0.5,-0.24)},anchor=north},\n",
            "  legend columns=3,\n",
            "]\n",
        ]
    )
    for index, (group, points) in enumerate(zip(groups, steps, strict=True), start=1):
        style = _LINE_STYLES[(index - 1) % len(_LINE_STYLES)]
        thickness = "very thick" if index >= len(groups) - 1 else "semithick"
        coordinates = " ".join(
            f"({_number(x)},{_number(y)})" for x, y in points
        )
        lines.append(
            f"\\addplot[{style},{thickness},color=pigEcdf{index}] "
            f"coordinates {{{coordinates}}};\n"
        )
        lines.append(f"\\addlegendentry{{{_escape(group.label)}}}\n")
    lines.extend(["\\end{axis}\n", "\\end{tikzpicture}\n"])
    return "".join(lines)


def _standalone() -> str:
    return (
        "\\documentclass[border=2pt]{standalone}\n"
        "\\usepackage[T1]{fontenc}\n"
        "\\usepackage{lmodern}\n"
        "\\usepackage{pgfplots}\n"
        "\\begin{document}\n"
        "\\input{\\jobname.tikz}\n"
        "\\end{document}\n"
    )


def _number(value: float) -> str:
    return format(float(value), ".12g")


def _escape(value: str) -> str:
    replacements = {
        "\\": "\\textbackslash{}",
        "&": "\\&",
        "%": "\\%",
        "$": "\\$",
        "#": "\\#",
        "_": "\\_",
        "{": "\\{",
        "}": "\\}",
    }
    return "".join(replacements.get(character, character) for character in value)
