"""Collision-safe paths for one generated instance and its artifacts."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re


_EXTENSION = re.compile(r"^\.[A-Za-z0-9]+$")
_SUFFIX = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")


@dataclass(frozen=True, slots=True)
class InstanceArtifactPaths:
    """Paths sharing one stable instance stem below an experiment directory."""

    stem: str
    instance_file: Path
    plot_directory: Path
    log_directory: Path
    merge_plot_directory: Path | None
    merge_log_directory: Path | None

    @property
    def gurobi_log(self) -> Path:
        return self.log_directory / "gurobi.log"


def allocate_instance_artifacts(
    run_directory: str | Path,
    bus_count: int,
    *,
    extension: str,
    suffix: str | None = None,
    instance_tree: str = "instances",
) -> InstanceArtifactPaths:
    """Reserve ``<buses>``, then ``<buses>_2``, etc. across all artifact trees.

    ``suffix`` extends every stem to ``<buses>_<suffix>`` so instances with the
    same node count generated by independent jobs stay distinguishable once
    their result directories are consolidated. It must be a single safe
    filename component.
    ``instance_tree`` is either ``instances`` for final composites or
    ``subinstances`` for extracted BFS pieces.
    """

    if isinstance(bus_count, bool) or not isinstance(bus_count, int) or bus_count < 1:
        raise ValueError("bus_count must be a positive integer")
    if not _EXTENSION.fullmatch(extension):
        raise ValueError("extension must look like '.m' or '.xml'")
    if suffix is not None and not _SUFFIX.fullmatch(suffix):
        raise ValueError("suffix must be a single safe filename component")
    if instance_tree not in {"instances", "subinstances"}:
        raise ValueError("instance_tree must be 'instances' or 'subinstances'")

    root = Path(run_directory)
    instance_directory = root / instance_tree
    plot_root = root / "plots"
    log_root = root / "logs"
    category = "composite" if instance_tree == "instances" else "original"
    plot_root = plot_root / category
    log_root = log_root / category
    for directory in (instance_directory, plot_root, log_root):
        directory.mkdir(parents=True, exist_ok=True)

    base = str(bus_count) if suffix is None else f"{bus_count}_{suffix}"
    occurrence = 1
    while True:
        stem = base if occurrence == 1 else f"{base}_{occurrence}"
        instance_file = instance_directory / f"{stem}{extension}"
        plot_directory = plot_root / stem
        log_directory = log_root / stem
        merge_plot_directory = (
            root / "plots" / "merged" / stem
            if instance_tree == "instances"
            else None
        )
        merge_log_directory = (
            root / "logs" / "merged" / stem
            if instance_tree == "instances"
            else None
        )
        merge_paths = tuple(
            path
            for path in (merge_plot_directory, merge_log_directory)
            if path is not None
        )
        if not (
            instance_file.exists()
            or plot_directory.exists()
            or log_directory.exists()
            or any(path.exists() for path in merge_paths)
        ):
            plot_directory.mkdir()
            log_directory.mkdir()
            for path in merge_paths:
                path.mkdir(parents=True)
            return InstanceArtifactPaths(
                stem=stem,
                instance_file=instance_file,
                plot_directory=plot_directory,
                log_directory=log_directory,
                merge_plot_directory=merge_plot_directory,
                merge_log_directory=merge_log_directory,
            )
        occurrence += 1
